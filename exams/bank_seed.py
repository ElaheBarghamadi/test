@transaction.atomic
def seed_question_bank(teacher):
    """ساخت/تکمیل بانک نمونه برای معلم. خروجی: (تعداد پوشهٔ جدید، تعداد سوال جدید)"""
    from exams.models import BankFolder, QuestionBank

    new_folders = new_questions = 0
    cache = {}

    def folder_for(path):
        nonlocal new_folders
        parent = None
        for i in range(len(path)):
            key = tuple(path[:i + 1])
            if key not in cache:
                obj, created = BankFolder.objects.get_or_create(
                    teacher=teacher, parent=parent, name=path[i][:80])
                new_folders += created
                cache[key] = obj
            parent = cache[key]
        return parent

    for path, spec in iter_bank():
        folder = folder_for(path)
        data = _build(spec)
        data['max_score'] = Decimal(str(data['max_score']))
        if QuestionBank.objects.filter(teacher=teacher, folder=folder, text=data['text']).exists():
            continue
        QuestionBank.objects.create(teacher=teacher, folder=folder, **data)
        new_questions += 1
    return new_folders, new_questions
